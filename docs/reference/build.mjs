// Builds the formula reference page and regenerates tools/romcheck/reference.zig
// from its Zig blocks, so the page and the ROM-checked ports can't drift apart.
//
//   node docs/reference/build.mjs
//
// Then `zig test tools/romcheck/reference.zig` and `zig build romcheck`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8');

let html = read('template.html')
  .replace('/*TABLES*/', read('tables.zig').trimEnd())
  .replace('/*DATA*/', read('data.json').trim());
fs.writeFileSync(path.join(here, 'dw-reference.html'), html);

// Fail on a syntax error in the page script without running it.
const js = html.match(/<script>([\s\S]*?)<\/script>/)[1];
new Function(js);

const blocks = [...html.matchAll(/<script type="text\/x-zig"[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1].trim());
const header = [
  '//! Reference ports of Dragon Warrior (NES) mechanics, from the formula reference page.',
  '//! `zig build romcheck` runs each one against the original ROM routine in a 6502 interpreter.',
  '//! Copy what you need into the engine; keep these as the known-good baseline.',
  '//!',
  '//! Generated by docs/reference/build.mjs from docs/reference/template.html. Edit the page, not this file.',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'tools/romcheck/reference.zig'), header + '\n' + blocks.join('\n\n') + '\n');

console.log(`dw-reference.html: ${html.length} bytes; reference.zig: ${blocks.length} Zig blocks`);
