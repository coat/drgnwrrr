//! romextract: decodes bank 0's maps and NPC tables from a Dragon Warrior (U)
//! ROM with dw.Maps.fromBank0 (the decoder romcheck checks against the ROM)
//! and writes them out as Zig source. build.zig runs it, so the game is built
//! with the data and never reads the ROM itself.
//!
//!   romextract <rom.nes> <out.zig>
const std = @import("std");
const Io = std.Io;
const dw = @import("dw");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) fail("usage: romextract <rom.nes> <out.zig>", .{});
    const rom_path = args[1];

    const rom = Io.Dir.cwd().readFileAlloc(io, rom_path, arena, .limited(1 << 20)) catch |err|
        fail("can't read {s} ({t}). drgnwrrr builds its maps from a Dragon Warrior (U) ROM; pass -Drom=PATH.", .{ rom_path, err });
    if (rom.len < 16 + 4 * 0x4000 or !std.mem.eql(u8, rom[0..4], "NES\x1a") or rom[4] != 4)
        fail("{s} doesn't look like Dragon Warrior (U).", .{rom_path});

    const maps = try arena.create(dw.Maps);
    maps.* = .fromBank0(rom[16..][0..0x4000]);

    var out: Io.Writer.Allocating = .init(arena);
    try write(&out.writer, maps, std.fs.path.basename(rom_path));
    try Io.Dir.cwd().writeFile(io, .{ .sub_path = args[2], .data = out.written() });
}

fn fail(comptime fmt: []const u8, args: anytype) noreturn {
    std.debug.print("romextract: " ++ fmt ++ "\n", args);
    std.process.exit(1);
}

fn write(w: *Io.Writer, maps: *const dw.Maps, rom_name: []const u8) !void {
    try w.print(
        \\//! Bank 0's maps and NPC tables, generated by tools/romextract from {s}.
        \\//! Don't edit: build.zig regenerates it. See dw.Maps for the layout.
        \\const dw = @import("dw");
        \\
        \\pub const maps: dw.Maps = .{{
        \\    // One hex digit per tile nibble, one line per row.
        \\    .nibbles = hex(
        \\
    , .{rom_name});
    for (dw.map_headers, 0..) |h, m| {
        const width = @as(usize, h.max_x) + 1;
        const height = @as(usize, h.max_y) + 1;
        if (m > 0) try w.writeAll("        ++\n");
        try w.print("        // 0x{X:0>2} {s}, {d}x{d}\n", .{ m, dw.map_names[m], width, height });
        for (0..height) |y| {
            try w.writeAll("        \\\\");
            const row = maps.nibbles[dw.Maps.offsets[m] + y * width ..][0..width];
            for (row) |n| try w.writeByte("0123456789abcdef"[n]);
            try w.writeByte('\n');
        }
    }
    try w.writeAll(
        \\    ),
        \\    // Moving ($9734), then stationary ($974C): x | sprite << 5, y | facing << 5, dialogue.
        \\    .npcs = .{
        \\
    );
    for (maps.npcs, 4..) |tables, m| {
        try w.print("        // 0x{X:0>2} {s}\n        .{{\n", .{ m, dw.map_names[m] });
        for (tables) |r| {
            try w.print("            .{{ .len = {d}, .rec = .{{", .{r.len});
            for (r.rec, 0..) |rec, i| try w.print("{s}.{{ 0x{X:0>2}, 0x{X:0>2}, 0x{X:0>2} }}", .{ if (i == 0) " " else ", ", rec[0], rec[1], rec[2] });
            try w.writeAll(" } },\n");
        }
        try w.writeAll("        },\n");
    }
    try w.writeAll(
        \\    },
        \\};
        \\
        \\fn hex(comptime s: []const u8) [dw.Maps.size]u8 {
        \\    @setEvalBranchQuota(4 * s.len);
        \\    var out: [dw.Maps.size]u8 = undefined;
        \\    var n: usize = 0;
        \\    for (s) |c| {
        \\        out[n] = switch (c) {
        \\            '0'...'9' => c - '0',
        \\            'a'...'f' => c - 'a' + 10,
        \\            else => continue,
        \\        };
        \\        n += 1;
        \\    }
        \\    if (n != out.len) @compileError("romdata: wrong number of nibbles");
        \\    return out;
        \\}
        \\
    );
}
